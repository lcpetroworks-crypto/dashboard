function buildImageStudy(
  sampleId: string,
  kind: "microCT" | "sem",
  resolutionOrMag: { resolutionMicronsPerVoxel?: number; magnification?: string },
  wormholeVolumeMm3: number | undefined,
  notes: string
): ImageStudy {
  return {
    sampleId,
    ...resolutionOrMag,
    beforeSeed: `${sampleId}-${kind}-before`,
    afterSeed: `${sampleId}-${kind}-after`,
    beforeLabel: "Antes da Acidificação",
    afterLabel: "Depois da Acidificação",
    wormholeVolumeMm3,
    edsComposition:
      kind === "sem"
        ? [
            { mineral: "Ca", percent: 38.2 },
            { mineral: "O", percent: 47.6 },
            { mineral: "C", percent: 11.4 },
            { mineral: "Mg", percent: 1.9 },
            { mineral: "Si", percent: 0.9 },
          ]
        : undefined,
    notes,
  };
}

